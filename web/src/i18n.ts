export const STRINGS: Record<Locale, Record<string, string>> = { es: ES, en: EN };

/** Stored preference wins; else first Spanish/English navigator language; else English. */
export function resolveLocale(stored: string | null, langs: readonly string[]): Locale {
  if (stored === 'es' || stored === 'en') return stored;
  for (const raw of langs) {
    const base = raw.toLowerCase().split('-')[0];
    if (base === 'es') return 'es';
    if (base === 'en') return 'en';
  }
  return 'en';
}

const LOCALE_KEY = 'override.locale';

export function loadLocale(): string | null {
  try {
    return typeof localStorage === 'undefined' ? null : localStorage.getItem(LOCALE_KEY);
  } catch {
    return null;
  }
}

export function saveLocale(locale: Locale): void {
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(LOCALE_KEY, locale);
  } catch {
    // Private mode etc: the session locale still applies.
  }
}

let current: Locale = 'es';

export const getLocale = (): Locale => current;

export const setLocale = (locale: Locale): void => {
  current = locale;
};

/** Translated string with {placeholder} interpolation. Falls back to English, then the key. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[current][key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
